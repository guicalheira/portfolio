// Converte os literais do `as const` em string, mantendo a estrutura,
// para que todos os idiomas compartilhem o mesmo tipo.
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : { readonly [K in keyof T]: Widen<T[K]> }

export type Translations = Widen<typeof translations.pt>
